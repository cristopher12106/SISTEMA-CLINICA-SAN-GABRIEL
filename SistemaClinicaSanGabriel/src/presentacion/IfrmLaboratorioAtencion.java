    public void cargarTablaExamenes() {
        DefaultTableModel modelo = (DefaultTableModel) tblExamenes.getModel();
        modelo.setRowCount(0);
        try {
            List<ExamenLaboratorio> lista = laboratorioLOG.listarSolicitudesPendientes();
            for (ExamenLaboratorio ex : lista) {
                modelo.addRow(new Object[]{
                    ex.getIdExamen(),
                    ex.getIdPaciente(),
                    ex.getTipoExamen(),
                    ex.getEstado(),
                    ex.getFechaSolicitud()
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la lista de exámenes: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
