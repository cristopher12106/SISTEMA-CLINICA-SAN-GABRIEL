    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        try {
            if (txtIdExamen.getText().trim().isEmpty() || txtResultado.getText().trim().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Debe seleccionar un examen e ingresar el resultado.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
                return;
            }
            int idExamen = Integer.parseInt(txtIdExamen.getText().trim());
            String resultadoStr = txtResultado.getText().trim();
            boolean exito = laboratorioLOG.registrarResultado(idExamen, resultadoStr, "");
            if (exito) {
                JOptionPane.showMessageDialog(this, "¡Resultado del examen registrado con éxito!", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                limpiarCampos();
                cargarTablaExamenes(); // Refresca la tabla
            } else {
                JOptionPane.showMessageDialog(this, "No se pudo registrar el resultado.", "Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID de Examen debe ser un número entero válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, e.getMessage(), "Error de Negocio", JOptionPane.WARNING_MESSAGE);
        }  // TODO add your handling code here:
    }//GEN-LAST:event_btnGuardarActionPerformed


